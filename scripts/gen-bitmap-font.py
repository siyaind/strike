"""Rasterise 'Press Start 2P' (SIL Open Font License 1.1, by CodeMan38) at its native 8px grid into a
1-bit glyph table used by @strike/visual-engine. Deterministic: same TTF -> same table."""
import json, sys
from PIL import Image, ImageDraw, ImageFont
path = sys.argv[1]
f = ImageFont.truetype(path, 8)
glyphs = {}
for cp in list(range(32, 127)):
    ch = chr(cp)
    im = Image.new('L', (16, 16), 0)
    d = ImageDraw.Draw(im)
    d.text((0, 0), ch, font=f, fill=255)
    rows = []
    for y in range(8):
        bits = 0
        for x in range(8):
            if im.getpixel((x, y)) > 127: bits |= (1 << (7 - x))
        rows.append(bits)
    glyphs[ch] = rows
print("// GENERATED by scripts/gen-bitmap-font.py from 'Press Start 2P' (SIL OFL 1.1). Do not edit by hand.")
print("export const GLYPH_W = 8\nexport const GLYPH_H = 8")
print("export const GLYPHS: Record<string, number[]> = " + json.dumps(glyphs, ensure_ascii=True))
